#!/usr/bin/env python3
"""Build one convex-hull collision mesh for every V3.2 hand link.

The active latest-project contract does not preserve raw CAD collision meshes:
every link gets one convex hull of its bundled per-link mesh. Visual meshes,
mass, inertia and joints stay unchanged by this maintenance utility.
"""
import argparse
import hashlib
import json
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'tsensei_v3_2_pianist' / 'assets'
PRESERVE_ORIGINAL = set()


def read_stl_vertices(path):
    data = path.read_bytes()
    if len(data) >= 84:
        try:
            count = struct.unpack_from('<I', data, 80)[0]
            if 84 + 50 * count == len(data):
                values = []
                for i in range(count):
                    off = 84 + 50 * i
                    values.extend(struct.unpack_from('<9f', data, off + 12))
                return np.asarray(values, dtype=np.float64).reshape(-1, 3)
        except (struct.error, ValueError):
            pass
    text = data.decode('utf-8', errors='ignore')
    rows = []
    for line in text.splitlines():
        parts = line.strip().split()
        if len(parts) == 4 and parts[0].lower() == 'vertex':
            rows.append([float(value) for value in parts[1:]])
    if not rows:
        raise ValueError(f'No STL vertices found: {path}')
    return np.asarray(rows, dtype=np.float64)


def write_binary_stl(path, vertices, hull):
    triangles = vertices[hull.simplices]
    with path.open('wb') as stream:
        header = b'TsenseI convex hull collision mesh'.ljust(80, b' ')
        stream.write(header)
        stream.write(struct.pack('<I', len(triangles)))
        for triangle, equation in zip(triangles, hull.equations):
            # Qhull simplices are not consistently wound. Orient every face
            # outward so MuJoCo renders a closed hull instead of missing faces.
            triangle = triangle.copy()
            if np.dot(np.cross(triangle[1]-triangle[0], triangle[2]-triangle[0]), equation[:3]) < 0:
                triangle[[1, 2]] = triangle[[2, 1]]
            normal = np.cross(triangle[1] - triangle[0], triangle[2] - triangle[0])
            length = np.linalg.norm(normal)
            if length:
                normal /= length
            stream.write(struct.pack('<3f', *normal.astype(np.float32)))
            for vertex in triangle:
                stream.write(struct.pack('<3f', *vertex.astype(np.float32)))
            stream.write(struct.pack('<H', 0))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-config', type=Path,
                        default=ASSETS / 'collision_proxies_convex_hull.json')
    parser.add_argument('--hull-dir', type=Path,
                        default=ASSETS / 'collision_hulls')
    args = parser.parse_args()
    args.hull_dir.mkdir(parents=True, exist_ok=True)
    config = {
        'schema': 1,
        'profile': 'convex_hull_v1',
        'units': 'metres; body-local URDF frame; MuJoCo quaternion wxyz',
        'reference': 'ConvexHull of each bundled URDF collision mesh; generated by scripts/generate_collision_hulls.py',
        'preserve_original_mesh_links': sorted(PRESERVE_ORIGINAL),
        'limitations': [
            'Convex hulls fill concave cavities by design; they are an outer collision approximation, not a watertight CAD replacement.',
            'Every link uses a convex hull; no raw CAD collision mesh is preserved.',
            'The active training profile is convex_hull_v1; shadow_primitive_v1 is a deprecated hull-only alias.',
        ],
        'hands': {},
    }
    for side in ('left', 'right'):
        urdf_path = ASSETS / 'urdf' / f'TsenseI_{side}.urdf'
        root = ET.parse(urdf_path).getroot()
        entries = {}
        out_dir = args.hull_dir / side
        out_dir.mkdir(parents=True, exist_ok=True)
        for link in root.findall('link'):
            name = link.get('name')
            collision = link.find('collision')
            mesh = None if collision is None else collision.find('geometry/mesh')
            if mesh is None:
                raise ValueError(f'Missing collision mesh for {side}/{name}')
            source = (urdf_path.parent / mesh.get('filename')).resolve()
            entry = {
                'source_mesh': str(source.relative_to(ASSETS)),
                'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
            }
            if name in PRESERVE_ORIGINAL:
                raise AssertionError('PRESERVE_ORIGINAL must remain empty for the active convex-hull contract')
            else:
                vertices = read_stl_vertices(source)
                scale = np.fromstring(mesh.get('scale', '1 1 1'), sep=' ')
                vertices *= scale
                unique = np.unique(np.round(vertices, decimals=12), axis=0)
                if len(unique) < 4:
                    raise ValueError(f'Not enough unique vertices for convex hull: {side}/{name}')
                hull = ConvexHull(unique)
                target = out_dir / f'{name}_convex_hull.stl'
                write_binary_stl(target, unique, hull)
                entry.update(
                    type='mesh',
                    mesh_file=str(target.relative_to(ASSETS)),
                    physical_role='rigid_mount' if 'palm' in name.lower() else 'finger_link',
                    hull_method='scipy_convex_hull_v1',
                    source_vertex_count=int(len(unique)),
                    hull_vertex_count=int(len(hull.vertices)),
                    hull_triangle_count=int(len(hull.simplices)),
                    reason='Convex hull of the full URDF collision mesh to cover the complete outer collision region',
                    hull_sha256=hashlib.sha256(target.read_bytes()).hexdigest(),
                )
            entries[name] = entry
        config['hands'][side] = entries
    args.output_config.write_text(json.dumps(config, indent=2) + '\n')
    print(args.output_config)
    print('generated hull meshes:', sum(1 for side in config['hands'].values() for e in side.values() if 'mesh_file' in e))


if __name__ == '__main__':
    main()
